const matchingMission = (levelId, order, terms, count = 5) => {
  const pairs = terms.slice(0, count).map((item) => ({ left: item.hanzi, right: item.thai, pinyin: item.pinyin }));
  return mission({
    levelId,
    order,
    type: "matching",
    beforeAnswer: {
      title: "ภารกิจจับคู่ฮั่นจื้อ",
      instruction: "เลือกคำจีนทางซ้าย แล้วเลือกคำแปลไทยทางขวาเพื่อโยงคู่ให้ครบ แตะคู่ที่โยงแล้วเพื่อยกเลิก",
      leftCards: pairs.map((pair) => pair.left),
      leftPinyin: Object.fromEntries(pairs.map((pair) => [pair.left, pair.pinyin])),
      rightCards: pairs.map((pair) => pair.right),
    },
    answer: {
      pairs,
      correctAnswer: Object.fromEntries(pairs.map((pair) => [pair.left, pair.right])),
    },
    afterAnswer: reveal({
      chineseText: pairs.map((pair) => pair.left).join(" / "),
      pinyin: pairs.map((pair) => pair.pinyin).join(", "),
      thaiMeaning: pairs.map((pair) => pair.right).join(" / "),
      explanation: "เมื่อคำจีนและคำแปลตรงกัน เส้นพลังจะเชื่อมคู่ให้สว่างขึ้น",
    }),
    hint: "สังเกตรูปร่างตัวอักษรและทบทวนหมวดคำศัพท์ทีละใบ",
    audioText: pairs[0].left,
    mechanics: { shuffleSidesIndependently: true },
  });
};

